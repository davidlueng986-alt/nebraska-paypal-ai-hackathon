// Regenerates fixtures/*.json from a real run of the simulation (demo mode, in-memory store).
// Everything here is SIMULATED and fictional; nothing touches PayPal.
import { mkdir, writeFile } from "node:fs/promises";
import { SqliteStore } from "../src/core/store";
import { Nebraska } from "../src/core/service";
import { DemoDecisionProvider } from "../src/core/decisions";
import { DemoPayments } from "../src/integrations/paypal";
import { seedDemo } from "../src/core/seed";
import { runMonthEnd } from "../src/core/monthend";
import { maintainerView, payerView } from "../src/core/views";

const period = "2026-11";
const store = new SqliteStore(":memory:");
const service = new Nebraska(store, new DemoDecisionProvider(), new DemoPayments());
await seedDemo(service, period);
await service.captureGrant((await store.read()).grants[0].id);
const events = await runMonthEnd(service, period, "run_2026-11_demo");
const s = await store.read();
const actor = { role: "admin" as const, id: "demo", exp: Infinity };
const write = (f: string, v: unknown) =>
  writeFile(`fixtures/${f}`, JSON.stringify(v, null, 2) + "\n");
await mkdir("fixtures", { recursive: true });
await write("month-end-run.json", {
  simulated: true,
  note: "Fictional identities. Generated by scripts/fixtures.ts against the demo-mode services; no PayPal call was made.",
  run_id: "run_2026-11_demo",
  events,
});
await write("payer-month.json", {
  simulated: true,
  ...payerView(s, "org_acme", period, actor),
});
await write("maintainer-income.json", {
  simulated: true,
  ...maintainerView(s, "m3", period, actor),
});
console.log(`wrote ${events.length} events`);
await store.close();
